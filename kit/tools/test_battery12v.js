'use strict';
// Decode supplied battery records without connecting to a vehicle.
const assert = require('assert');
const fs = require('fs');
const path = require('path');
const vm = require('vm');
const root = path.resolve(__dirname, '../..');
const spec = JSON.parse(fs.readFileSync(path.join(root, 'apps/battery12v/app.json'), 'utf8'));
const source = fs.readFileSync(path.join(root, 'apps/battery12v/main.js'), 'utf8').replace(/\r\n/g, '\n');
const context = { G: { isNum: (v) => typeof v === 'number' && isFinite(v) } };
vm.createContext(context);
vm.runInContext(source.slice(source.indexOf('const W ='), source.indexOf('\nmgu.run(')) +
    '\nthis.api = { Reader, ocvSoc };', context);
const { Reader, ocvSoc } = context.api;
const cfg = spec.config.battery;
assert.strictEqual(spec.id, 'battery12v');
assert.strictEqual(cfg.ecu, 0x12);
assert.strictEqual(cfg.currentSign, -1);
const ibs = Reader.decode([0x62, 0x40, 0x2b, 0, 195, 0x86, 0x60, 7, 208], 3, cfg.ibs[0].fields);
assert(Math.abs(ibs.temp - 19.5) < 1e-6);
assert(Math.abs(ibs.volt - 14.6) < 1e-6);
assert(Math.abs(ibs.amp - (-40)) < 1e-6);
const invalid = Reader.decode([0x62, 0x40, 0x2b, 255, 255, 255, 255, 255, 255], 3, cfg.ibs[0].fields);
assert.strictEqual(invalid.volt, null);
assert.strictEqual(invalid.temp, null);
assert.strictEqual(invalid.amp, null);
assert.strictEqual(Reader.decode([0x62, 0x40, 0xa9, 90, 0, 90], 3, cfg.cap[0].fields).cap, 90);
assert.strictEqual(Reader.decode([0x62, 0x40, 0xad, 78], 3, cfg.soc[0].fields).soc, 78);
assert.strictEqual(Reader.decode([0x62, 0x40, 0xad, 101], 3, cfg.soc[0].fields).soc, null);
assert.strictEqual(Reader.decode([0x62, 0xf4, 0x42, 0x39, 0x08], 3, cfg.volt[0].fields).volt, 14.6);
assert(Math.abs(ocvSoc(12.6, 'agm') - 70) < 1e-6);
assert.strictEqual(ocvSoc(null, 'agm'), null);
console.log('PASS: Battery12v IBS/DME voltage, current, temperature, SOC/capacity, invalid data and voltage estimate');
